#!/usr/bin/env node
// Writes src/sim/vsop87.ts: the planetary theory VSOP87B (Bretagnon & Francou
// 1988; heliocentric ecliptic spherical coordinates, J2000), truncated for the
// planets the app shows beyond Mars, and the Earth they are seen from.
//
// The full series has 3,000-9,000 terms per planet and is good to milliarcseconds.
// A term whose amplitude (times τ^α at τ = 0.1 millennium) is under 2e-6 rad
// (0.4″) or 2e-6 au is dropped, leaving ~980 terms in all: every planet within
// ~4″ of JPL Horizons over 2020-2035 (sim/planets.test.ts). Standish's Keplerian
// elements, which still place Mars and the Earth, are 5′ off for Saturn.
//
// Source: IMCCE, ftp.imcce.fr/pub/ephem/planets/vsop87 (cached in data/cache).

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const cache = join(root, 'data', 'cache');
const PLANETS = { mercury: 'mer', venus: 'ven', earth: 'ear', jupiter: 'jup', saturn: 'sat', uranus: 'ura', neptune: 'nep' };
const EPS = 2e-6;

async function source(ext) {
  const p = join(cache, `VSOP87B.${ext}`);
  if (!existsSync(p)) {
    const url = `https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87B.${ext}`;
    console.log(`downloading ${url}`);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} for ${url}`);
    writeFileSync(p, await res.text());
  }
  return readFileSync(p, 'utf8');
}

/** [variable L/B/R][power of τ] -> flat [A, B, C, A, B, C, ...], truncated */
function parse(text) {
  const out = [[], [], []];
  for (const line of text.split('\n')) {
    if (!line.trim() || line.includes('VSOP87')) continue;
    const head = line.slice(0, 5).trim();
    const v = +head[2] - 1, alpha = +head[3];
    const [A, B, C] = line.trim().split(/\s+/).slice(-3).map(Number);
    const series = (out[v][alpha] ??= []);
    if (Math.abs(A) * 0.1 ** alpha > EPS) series.push(A, B, C);
  }
  return out;
}

const fmt = (x) => (x === 0 ? '0' : Number(x.toPrecision(11)).toString());
let ts = `// Generated by scripts/vsop.mjs from VSOP87B (Bretagnon & Francou 1988, IMCCE). Do not edit.
// Per planet: [L, B, R], each a list by power of τ (Julian millennia TDB from J2000)
// of flattened [A, B, C] terms: value += A cos(B + C τ) τ^α. L and B in rad, R in au.

export type Series = number[][];
export const VSOP87: Record<string, [Series, Series, Series]> = {\n`;
let total = 0;
for (const [name, ext] of Object.entries(PLANETS)) {
  const s = parse(await source(ext));
  const n = s.flat().reduce((a, t) => a + t.length / 3, 0);
  total += n;
  console.log(`${name}: ${n} terms`);
  ts += `  ${name}: [\n${s.map((byAlpha) => `    [\n${byAlpha.map((t) => `      [${t.map(fmt).join(',')}],`).join('\n')}\n    ],`).join('\n')}\n  ],\n`;
}
ts += '};\n';
const out = join(root, 'web', 'src', 'sim', 'vsop87.ts');
writeFileSync(out, ts);
console.log(`${out.replace(root + '/', '')}: ${total} terms, ${(ts.length / 1024).toFixed(0)} KiB`);
